import json
from typing import Any

import pandas as pd

from src.llm import get_llm


class SemanticAnalyzer:
    """
    Uses an LLM to infer the semantic meaning of a structured dataset.

    The analyzer does not modify the dataset.
    It only produces semantic metadata that downstream agents can use.
    """

    def __init__(self):
        self.llm = get_llm()

    def analyze(
        self,
        df: pd.DataFrame,
        profile: dict[str, Any],
    ) -> dict[str, Any]:
        """
        Analyze the semantic meaning of the dataset.

        Parameters
        ----------
        df:
            Original Pandas DataFrame.

        profile:
            Deterministic dataset profile generated by the profiler.

        Returns
        -------
        dict
            Structured semantic understanding of the dataset.
        """

        if not isinstance(df, pd.DataFrame):
            raise TypeError("Expected a Pandas DataFrame.")

        if not profile:
            raise ValueError("Dataset profile cannot be empty.")

        context = self._build_context(df, profile)

        prompt = self._build_prompt(context)

        response = self.llm.invoke(prompt)

        return self._parse_response(response.content)

    def _build_context(
        self,
        df: pd.DataFrame,
        profile: dict[str, Any],
    ) -> dict[str, Any]:
        """
        Build a compact representation of the dataset for the LLM.

        We intentionally do not send the entire dataset to the model.
        """

        sample_size = min(len(df), 10)

        sample = df.head(sample_size).copy()

        sample = sample.astype(object).where(
            pd.notna(sample),
            None,
        )

        return {
            "dataset_shape": {
                "rows": len(df),
                "columns": len(df.columns),
            },
            "profile": profile,
            "sample_rows": sample.to_dict(orient="records"),
        }

    def _build_prompt(self, context: dict[str, Any]) -> str:
        """
        Construct the semantic-analysis prompt.
        """

        context_json = json.dumps(
            context,
            indent=2,
            default=str,
        )

        return f"""
You are a data semantics expert working inside an autonomous
business intelligence system.

Your task is to understand the meaning and structure of a
structured business dataset.

You are given:
1. Deterministic dataset profiling information.
2. A small representative sample of the dataset.

Do NOT calculate business results.
Do NOT invent facts that cannot reasonably be inferred.
Do NOT modify the dataset.

Your task is to infer:

- What the dataset appears to represent.
- The semantic role of each column.
- Which columns are identifiers.
- Which columns are dimensions.
- Which columns are measures.
- Which columns represent dates or time.
- Which columns are categorical.
- Which columns may represent monetary values.
- Which columns may be useful for grouping or segmentation.
- Potential relationships between columns.
- Potential derived business metrics that could reasonably be calculated.
- Potential data-quality concerns.

Return ONLY valid JSON using this structure:

{{
    "dataset_description": "Short description of what the dataset represents",

    "columns": {{
        "column_name": {{
            "semantic_role": "identifier | dimension | measure | datetime | categorical | unknown",
            "description": "Meaning of the column",
            "business_relevance": "Why this column may matter",
            "possible_unit": "unit if inferable, otherwise null"
        }}
    }},

    "relationships": [
        {{
            "columns": ["column_a", "column_b"],
            "relationship": "Description of the likely relationship"
        }}
    ],

    "potential_derived_metrics": [
        {{
            "name": "Metric name",
            "formula": "Possible formula",
            "reason": "Why this metric may be useful"
        }}
    ],

    "data_quality_concerns": [
        "Potential issue 1",
        "Potential issue 2"
    ]
}}

Dataset context:

{context_json}
"""

    def _parse_response(self, response: str) -> dict[str, Any]:
        """
        Parse the LLM response into a Python dictionary.
        """

        response = response.strip()

        # Handle accidental Markdown code fences.
        if response.startswith("```"):
            response = response.replace("```json", "")
            response = response.replace("```", "")
            response = response.strip()

        try:
            result = json.loads(response)
        except json.JSONDecodeError as exc:
            raise ValueError(
                "LLM returned invalid JSON."
            ) from exc

        if not isinstance(result, dict):
            raise ValueError(
                "Semantic analysis result must be a JSON object."
            )

        return result